# left the 1D targets and the circle, right the other 2D targets; rows align block by block.
REG_A_SIDES = (["trimodal", "inhom", "circle"], ["checkerboard", "spirals", "gauss8"])
REG_A_SEP = r"@{\hspace{1.5em}}"
# rule labels under the column header lambda(t)
REG_A_RULE = {"oracle": "oracle", "holdout": "hold-out"}


def _reg_a_block(S, case):
    """[([k, rule], [Cell])] of one target of tab_reg_full, None marking an \\addlinespace;
    k (digit) on the first row of its group only."""
    rows = []
    for g, (reg, _) in enumerate(REG_PENALTIES):
        if g:
            rows.append(None)
        for i, (rule, _) in enumerate(REG_RULES):
            rows.append(([f"${C.PENALTY_OP[reg]}$" if i == 0 else "", REG_A_RULE[rule]],
                         [cell(reg_flow_tv(S, case, reg, rule, n)) for n in C.SIZES]))
    return rows


def _reg_a(S):
    labels = {c: dim_label(c, lab) for c, lab in REG_CASES}
    k = len(C.SIZES)
    body = []
    for lc, rc in zip(*REG_A_SIDES):
        body += [r"\midrule",
                 fr"\multicolumn{{{2 + k}}}{{l}}{{\emph{{{labels[lc]}}}}} & "
                 fr"\multicolumn{{{2 + k}}}{{l}}{{\emph{{{labels[rc]}}}}} \\"]
        for left, right in zip(_reg_a_block(S, lc), _reg_a_block(S, rc)):
            if left is None:
                body.append(r"\addlinespace")
                continue
            body.append((left[0], left[1] + right[0] + right[1]))
    # a half has k cell columns, then the two right labels: column j pairs with j + k + 2
    lines, exps = render(body, groups=[(j, j + k + 2) for j in range(k)],
                         fixed=tv_cols(list(range(k)) + list(range(k + 2, 2 * k + 2))))
    head = r"$k$ & $\lambda(t)$ & " + " & ".join(f"$N = {n}$" for n in C.SIZES)
    tab = [r"\begin{tabular}{cl" + "c" * k + REG_A_SEP + "cl" + "c" * k + "}", r"\toprule",
         head + " & " + head + r" \\"]
    return tab + power_row(2, exps) + lines + [r"\bottomrule", r"\end{tabular}"]


def _reg_b_groups(S, case):
    """Panel (b) of tab_refine_1d / _2d for one target: rows per penalty, [[([penalty, m],
    [Cell])]], the penalty on the first row of its group; in 2D each group ends with the
    extra resolution (extra_holdout)."""
    groups = []
    for reg, plab in REG_PENALTIES:
        d = S[controls_name(case, reg)]
        rows = [([plab if i == 0 else "", str(m)],
                 [cell(rowp(d, f"{case}/m{m}/holdout/tv_pos", n)) for n in C.SIZES])
                for i, m in enumerate(controls_ms(d, case))]
        if CASE_DIM[case] == 2:
            need = config.CONTROLS_M_EXTRA.get(case, {}).get("holdout_ns", {}).get(reg, ())
            for m, dx, key in extra_holdout(S, reg, case):
                rows.append((["", str(m)], [cell(rowq(dx, key, n, need)) for n in C.SIZES]))
        groups.append(rows)
    return groups


# tab_refine_1d / _2d: columns k and m, two targets side by side;
# per target two blocks under in-line headings, the hold-out flows of k = 2, 1, 0, then
# lambda -> 0 (k empty). The heading carries lambda -> 0 so that the k column
# holds digits only.
REFINE_CASES = {1: list(C.DATASETS), 2: [t for t, _ in TWOD_CASES]}
REFINE_PAIRS = {1: [("trimodal", "inhom")],
                2: [("circle", "checkerboard"), ("spirals", "gauss8")]}
REFINE_NAME = {**C.DATASET_LABEL, **dict(TWOD_CASES)}
# (heading suffix, groups of _refine_groups) per block, in table order
REFINE_BLOCKS = ((r"$\nabla^k$ regularizer", slice(1, None)), (r"$\lambda \to 0$", slice(0, 1)))
REFINE_SEP = r"@{\hspace{1.5em}}"
# Column padding per dimension, None for the default: as TWOD_TABCOLSEP, the largest value in
# 0.5pt steps within \textwidth at \footnotesize for 1D (pdflatex: 365.0pt at 5.5pt, 373.0pt
# at the default 6pt); 2D takes the same value so that both tables share the spacing.
REFINE_TABCOLSEP = {1: "5.5pt", 2: "5.5pt"}


def _refine_groups(S, case):
    """[(k label, [(m, [Cell])])] of one target: lambda -> 0 (iid latents, _refine_a_groups;
    k label empty, its heading names it), then the hold-out flows of k = 2, 1, 0
    (_reg_b_groups). REFINE_BLOCKS sets the table order (the regularizers first)."""
    groups = [("", [(lab[1], cells) for lab, cells in _refine_a_groups(S, case)[0]])]
    for (reg, _), rows in zip(REG_PENALTIES, _reg_b_groups(S, case)):
        groups.append((f"${C.PENALTY_OP[reg]}$", [(lab[1], cells) for lab, cells in rows]))
    return groups


def _refine_body(S, pairs):
    """Rows of the side-by-side table: per pair two blocks (REFINE_BLOCKS: the k = 2, 1, 0
    groups, then the lambda -> 0 group), each opened by an in-line heading row naming the left
    and the right target; the groups of both targets aligned (the shorter group padded with
    empty cells), k on the first row of its group only. Cells of a row: left 3 N cells, right
    k and m, right 3 N cells."""
    k = len(C.SIZES)
    pad = ("", [""] * k)
    head = lambda c, b: fr"\multicolumn{{{2 + k}}}{{l}}{{\emph{{{REFINE_NAME[c]}, {b}}}}}"
    body = []
    for lc, rc in pairs:
        lg, rg = _refine_groups(S, lc), _refine_groups(S, rc)
        body.append(r"\midrule")
        for b, (blab, sl) in enumerate(REFINE_BLOCKS):
            if b:
                body.append(r"\addlinespace")
            body.append(head(lc, blab) + " & " + head(rc, blab) + r" \\")
            body += _refine_rows(lg[sl], rg[sl], pad)
    return body


def _refine_rows(lgroups, rgroups, pad):
    """Rows of the aligned groups of one block of _refine_body, \addlinespace between groups."""
    body = []
    for g, ((lk, lrows), (rk, rrows)) in enumerate(zip(lgroups, rgroups)):
        if g:
            body.append(r"\addlinespace")
        for i in range(max(len(lrows), len(rrows))):
            lm, lcells = lrows[i] if i < len(lrows) else pad
            rm, rcells = rrows[i] if i < len(rrows) else pad
            body.append(([lk if i == 0 and lm else "", lm],
                         list(lcells) + [rk if i == 0 and rm else "", rm] + list(rcells)))
    return body


def _refine(S, dim):
    """One tabular: k | m | N columns, twice (left and right target of a pair)."""
    k = len(C.SIZES)
    tv = list(range(k)) + list(range(k + 2, 2 * k + 2))
    lines, exps = render(_refine_body(S, REFINE_PAIRS[dim]), fixed=tv_cols(tv))
    half = "$k$ & $m$ & " + " & ".join(f"$N = {n}$" for n in C.SIZES)
    sep = REFINE_TABCOLSEP[dim]
    tab = ([fr"\setlength{{\tabcolsep}}{{{sep}}}%"] if sep else []) + [
        r"\begin{tabular}{@{}ll" + "c" * k + REFINE_SEP + "ll" + "c" * k + "@{}}", r"\toprule",
        half + " & " + half + r" \\"]
    return tab + power_row(2, exps) + lines + [r"\bottomrule", r"\end{tabular}"]


