class Cell(NamedTuple):
    """One numeric table entry before formatting: the column's power of ten is known only
    once every row of the column exists."""
    mean: float
    se: float = np.nan
    bold: bool = False
    pending: bool = False
    mark: str = ""          # text appended to the formatted entry (tab_lam_sweep_full markers)


def cell(v, bold=False) -> Cell:
    m, se = stats(v)
    return Cell(m, se, bold, v is PENDING)


# One TV unit in every table: TV columns print in units of
# 10^TV_E = 10^-2 (percent) with one decimal, as tab_main, so that N = 100 and N >= 1000 read
# digit by digit (render(fixed=...)).
TV_E = -2
TV_ONLY_NOTE = "% Entries are TV in units of 10^-2 (percent) in every column, one decimal place.\n"


def tv_cols(cols) -> dict:
    """render(fixed=...) entry of the TV cell columns cols: the unit 10^TV_E."""
    return {j: TV_E for j in cols}


# Shading of the rows an appendix table shares with tab_main (tab_oned_full: select_oned, tab_twod_full:
# select_twod); \rowcolor needs \usepackage[table]{xcolor} in main.tex. It
# stands on its own line before the row (a newline is a space, so it still opens the row).
SHADE = r"\rowcolor{black!8}"
ROT_BLOCK_NOTE = (
    "% First column: the target, rotated (tab_main's labels, MAIN_ROT_LABEL), \\multirow over\n"
    "% its block from the block's last row (negative row count), so that the \\rowcolor of a\n"
    "% shaded row does not paint over it; the label cell of a shaded row is \\cellcolor{white}.\n"
    "% Needs \\usepackage{multirow}, graphicx (\\rotatebox) and xcolor[table].\n")


def render(body, groups=(), fixed=None):
    """LaTeX lines of a tabular body and the per-column exponents.

    body: raw lines (str) and rows (labels, cells) or (labels, cells, shade), labels a list
    of str, cells a list of Cell or str; a true shade puts SHADE before the row. Column j of
    the cells gets the exponent of C.column_exponent over the Cell means in that column,
    across all rows of the body (blocks included). groups: tuples of cell columns that
    share one power (the halves of a side-by-side table), set over their union. fixed:
    {cell column: exponent} replacing the computed power (tv_cols: the TV unit)."""
    rows = [b[1] for b in body if not isinstance(b, str)]
    ncol = max((len(c) for c in rows), default=0)
    union = {j: g for g in groups for j in g}
    exps = [C.column_exponent([c[i].mean for i in union.get(j, (j,)) for c in rows
                               if i < len(c) and isinstance(c[i], Cell)]) for j in range(ncol)]
    for j, e in (fixed or {}).items():
        if j < ncol:
            exps[j] = e
    out = []
    for b in body:
        if isinstance(b, str):
            out.append(b)
            continue
        labels, cells, *shade = b
        txt = [(C.tbd() if x.pending else C.fmt_sci(x.mean, x.se, exps[j], x.bold) + x.mark)
               if isinstance(x, Cell) else x for j, x in enumerate(cells)]
        if shade and shade[0]:
            out.append(SHADE)
        out.append(" & ".join(list(labels) + txt) + r" \\")
    return out, exps


def power_row(nlab, exps):
    """Second header row with the column powers (empty list if every power is 0)."""
    if not any(exps):
        return []
    return [" & " * nlab + " & ".join(C.power_label(e) for e in exps) + r" \\"]


def _cells(values, flags):
    """Cells of a column of per-set arrays; bold the lowest mean among data-driven rows and
    every data-driven row whose difference to it is unresolved (unresolved_vs)."""
    st = [stats(v) for v in values]
    dd = [i for i, (s, f) in enumerate(zip(st, flags)) if f and np.isfinite(s[0])]
    best = min(dd, key=lambda i: st[i][0]) if dd else None
    bold = {best} if best is not None else set()
    bold |= {i for i in dd if i != best and unresolved_vs(values[i], values[best])}
    return [Cell(m, se, i in bold, v is PENDING) for i, ((m, se), v) in enumerate(zip(st, values))]


def _block_rows(S, d, rows, tv_fn, nsteps=None, shade=()):
    """Body rows of one dataset block, one TV column per N (tv_fn(S, d, method, n)); bolding
    is per column across the whole block. A '{rk}' in a label becomes the production
    integrator with nsteps steps. Rows whose method is in shade are shaded."""
    flat = [r for _, grp in rows for r in grp]
    cols = [_cells([tv_fn(S, d, m, n) for m, _, _ in flat], [f for _, _, f in flat])
            for n in C.SIZES]
    out, i = [], 0
    for g, (_, grp) in enumerate(rows):
        if g:
            out.append(r"\addlinespace")
        for m, label, _ in grp:
            out.append(([label.replace("{rk}", rk_label(nsteps))], [c[i] for c in cols],
                        m in shade))
            i += 1
    return out


def _head(exps, first="Estimator"):
    """Header of a blocked appendix table (tab_oned_full, tab_twod_full): the rotated target column
    (no header), the row label, one TV column per N; the layout of tab_main."""
    h = [r"\begin{tabular}{@{}cl" + "c" * len(C.SIZES) + "@{}}", r"\toprule",
         " & " + first + " & " + " & ".join(f"$N = {n}$" for n in C.SIZES) + r" \\"]
    return h + power_row(2, exps)


# Label cell of a shaded row: \rowcolor colours the whole row, the rotated label column
# included; white keeps that column plain beside the shaded rows.
WHITE_CELL = r"\cellcolor{white}"


def _rot_block(case, rows):
    """A block of _block_rows with the rotated target label (rot_lines, as tab_main) in a
    first column: in the LAST row (C.rot_label last=True), so that \rowcolor of a shaded
    row below the label's top cannot paint over it; the label cell of a shaded row is
    white."""
    nrow = sum(1 for b in rows if not isinstance(b, str))
    inner = sum(1 for b in rows if isinstance(b, str))
    out, i = [], 0
    for b in rows:
        if isinstance(b, str):
            out.append(b)
            continue
        labels, cells, *shade = b
        i += 1
        first = WHITE_CELL if shade and shade[0] else ""
        if i == nrow:
            first += C.rot_label(rot_lines(case), nrow, inner, last=True)
        out.append(([first] + list(labels), cells, *shade))
    return out


def rank(score_fn, cands):
    """[(method, score)] of the candidates, ascending, NaN last (ties keep the candidate
    order); score = average over N of the per-N mean over sets of score_fn(method, n), NaN,
    missing and pending entries ignored. The rule behind every 'best' row of a main table."""
    out = []
    for m in cands:
        means = [stats(score_fn(m, n))[0] for n in C.SIZES]
        means = [x for x in means if np.isfinite(x)]
        out.append((m, float(np.mean(means)) if means else np.nan))
    return sorted(out, key=lambda kv: (not np.isfinite(kv[1]), kv[1]))


class Selection(NamedTuple):
    """The rows of one block of a selection (select_oned, select_twod), in table order, and
    the rankings that chose its 'best' rows; tab_main takes the first four, the appendix
    table shades exactly methods."""
    methods: list            # method keys in main-table order
    rankings: list           # [(role, [(method, score)] ascending)]; the pick is the first

    def notes(self, block) -> list:
        """'%' comment lines naming the rows, the picks and the full rankings."""
        # '--': no finite TV (source pending or entries missing)
