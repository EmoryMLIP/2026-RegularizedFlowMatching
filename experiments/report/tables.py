def with_tbd(text: str) -> str:
    """text with the \\tbd definition after its leading comment lines if a table line uses
    \\tbd (so main.tex needs no new macro)."""
    lines = text.split("\n")
    if not any(TBD in ln for ln in lines if not ln.lstrip().startswith("%")):
        return text
    k = next((i for i, ln in enumerate(lines) if not ln.lstrip().startswith("%")), len(lines))
    return "\n".join(lines[:k] + [TBD_DEF] + lines[k:])


