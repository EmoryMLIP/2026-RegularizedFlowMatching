def twod_tv(S: Sources, target: str, method: str, n: int):
    """Per-set TV of a method on a 2D target, None if the source lacks the entry, PENDING if
    every source it could come from is missing: twod_eval_<T> (regenerated; reproduces the
    stored tv_pos) if present, else the stored tv_pos of twod_<T> / kde2d_<T>; unregularized
    rows tv_iid (lam -> 0 from controls_iid_<T>, lam0_tv); K4 rows from kde4_2d_<T>; the EM
    mixture from em8 (best)."""
    if method == "lam0":
        return lam0_tv(S, target, n)
    if method == "em8":
        d = S["em8"]
        return rowp(d, em8_key(d), n)
    if method.startswith("k4"):
        d = S[tname("kde4_2d", target)]
        return rowp(d, kde4_2d_key(d, target, method, "tv_pos"), n)
    ev = S[tname("twod_eval", target)]
    v = rowv(ev, f"{target}/{method}/{'tv_iid' if unreg(method) else 'tv_pos'}", n)
    if not unreg(method):
        # the stored tv_pos equals the regenerated one; prefer the source with more sets
        kde = method.startswith("kde_")
        alt = S[tname("kde2d" if kde else "twod", target)]
        k = (kde2d_key(alt, target, method, "tv_pos") if kde
             else twod_flow_key(alt, target, method, "tv_pos"))
        w = rowv(alt, k, n)
        check_same(v, w, f"{target}/{method}/tv_pos N={n} (twod_eval vs stored run)")
        count = lambda a: 0 if a is None else int(np.isfinite(a).sum())
        if count(w) > count(v):
            v = w
        if ev is None and alt is None:
            return PENDING
        return v
    return PENDING if ev is None else v


def select_twod(S: Sources, target: str) -> Selection:
    """Selected rows of a 2D target, the shading of tab_twod_full: FM oracle, FM hold-out, the
    best oracle KDE (every KDE row of TWOD_ROWS flagged not data-driven: the oracle rules and
    the anisotropic rules, whose LSCV uses the exact tangent), the best data-driven KDE
    (TWOD_KDE_DD) and spline lam = 0; best = first of rank() over twod_tv."""
    tv = lambda m, n: twod_tv(S, target, m, n)
    roles = [("oracle KDE", _cands(TWOD_ROWS, "KDE", False)),
             ("data-driven KDE", list(TWOD_KDE_DD))]
    rankings = [(role, rank(tv, c)) for role, c in roles]
    return Selection(["oracle", "holdout"] + [r[0][0] for _, r in rankings] + ["lam0"],
                     rankings)


