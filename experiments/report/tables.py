def _controls_b_err(S, ie):
    """tab_integrator: integration error of RK4 against the reference for the exact v_N
    (RK4 with step doubling) and the hold-out flow (DOP853) (integration_error.npz; \\tbd
    cells while it is missing; 2D blocks from integration_error_<T>.npz where present). The
    TV of the references, the converged level of the step doubling and the TV of the law
    rho_N(., t_end) go to the header comment."""
    k = len(C.SIZES)
    body, tvnote = [], []
    blocks = ie_blocks(S, ie)
    for c, ieb, lawsrc, lawkey in blocks:
        ev = S[lawsrc]
        get = (lambda key, n: PENDING) if ieb is None else (lambda key, n, d=ieb: C.row(d, key, n))
        body += [r"\midrule", fr"\multicolumn{{{2 + 2 * k}}}{{l}}{{\emph{{{CTL_LABEL[c]}}}}} \\"]
        for fi, (f, flab) in enumerate(IE_FLOWS):
            if fi:
                body.append(r"\addlinespace")
            for i, (g, steps) in enumerate(ie_rk(ieb)):
                cells = []
                for n in C.SIZES:
                    dx, dl = get(f"{c}/{f}/{g}/dx", n), get(f"{c}/{f}/{g}/dlogf", n)
                    # worst set: the integration error is a bound, not a sample statistic
                    cells.append(_ie_cell(dx, _max_dx))
                    cells.append(_ie_cell(dl, lambda a: np.nanmax(np.nanmean(np.abs(a), -1))))
                body.append(" & ".join([flab if i == 0 else "", str(steps)] + cells) + r" \\")
            if ieb is None:
                continue
            rkey, rlab = IE_REFERENCE[f]
            if f == "exact":
                lv = []
                for n in C.SIZES:
                    ns_ = C.row(ieb, f"{c}/{f}/{rkey}/ref_nstep", n)
                    cv = C.row(ieb, f"{c}/{f}/{rkey}/ref_converged", n)
                    ex = C.row(ieb, f"{c}/{f}/{rkey}/ref_err_x", n)
                    el = C.row(ieb, f"{c}/{f}/{rkey}/ref_err_logf", n)
                    em = C.row(ieb, f"{c}/{f}/{rkey}/ref_err_logf_max", n)
                    if ns_ is None or not np.isfinite(np.asarray(ns_, float)).any():
                        lv.append(f"N={n} --")
                        continue
                    lv.append(f"N={n} nstep {int(np.nanmax(ns_))}, converged "
                              f"{int(np.nansum(cv))}/{np.size(cv)} sets, max err_x "
                              f"{np.nanmax(ex):.1e}, max over sets of the mean |dlog f| "
                              f"{np.nanmax(el):.1e} and of the max "
                              f"{np.nanmax(em) if em is not None else np.nan:.1e}")
                tvnote.append(f"% reference {c}, exact (finest level over sets): " + "; ".join(lv))
            for lab, fn in ([(rlab, lambda n: rowv(ieb, f"{c}/{f}/{rkey}/tv", n))]
                            + ([("law rho_N(., t_end)",
                                 lambda n: rowv(ev, lawkey, n))]
                               if f == "exact" else [])):
                vals = []
                for n in C.SIZES:
                    mu_, se = stats(fn(n))
                    vals.append(f"N={n} {mu_:.4f} +- {se:.4f}")
                tvnote.append(f"% TV {c}, {f}, {lab}: " + ", ".join(vals))
    tab = [r"\begin{tabular}{ll" + "cc" * k + "}", r"\toprule",
           r" & & " + " & ".join(fr"\multicolumn{{2}}{{c}}{{$N = {n}$}}" for n in C.SIZES) + r" \\",
           "".join(fr"\cmidrule(lr){{{3 + 2 * j}-{4 + 2 * j}}}" for j in range(k)),
           r"Flow & RK4 steps & "
           + " & ".join([r"$\max |\Delta x|$ & $|\Delta \log f|$"] * k) + r" \\"]
    tab += body
    m = (int(ie["m_latents"]) if ie is not None and "m_latents" in ie
         else config.INTEGRATION_ERROR["m_lat"])
    ie_cfg = config.INTEGRATION_ERROR
    rc = config.REFERENCE_RK4
    note = (f"% Integration error to t_end = {config.T_END:g} against a reference on the same {m} "
            f"iid latents (rng {config.SEEDS['iid']} + set).\n"
            f"% Exact v_N: RK4 with step doubling from {nstep(ie) or config.NSTEP} steps, "
            f"converged when two consecutive levels differ by\n"
            f"% <= {rc['tol_x']:g} in x (frame units, max) and <= {rc['tol_logf']:g} in log f (mean) "
            f"(at most {rc['max_doublings']} doublings); v_N jumps at the box faces, where\n"
            "% adaptive error control stalls. FM, hold-out: solve_ivp DOP853 (rtol "
            f"{ie_cfg['rtol']:g}, atol {ie_cfg['atol']:g}).\n"
            "% max |Delta x| = max over sets and latents of |x_RK4(t_end) - x_ref(t_end)|;\n"
            "% |Delta log f| = max over sets of the mean over latents of |log f_RK4 - log f_ref|\n"
            "% (worst set in both). Entries in\n"
            "% scientific notation per entry (rows differ by design by orders of magnitude).\n"
            "% FM, hold-out: the production flow (lambda(t) from oned.npz, refit mode), whose RK4\n"
            f"% {nstep(ie) or config.NSTEP} TV the paper reports.\n"
            f"% TV (mean +- SE over sets, not printed in the table): reference = tv_pos over the {m}\n"
            "% latents (integration_error.npz); law = TV of rho_N(., t_end), the mixture of\n"
            "% box-truncated Gaussians, from direct draws (oned_eval.npz).\n")
    if len(blocks) > len(C.DATASETS):
        note += ("% 2D blocks (integration_error_<T>.npz, integration_error.py --target T):\n"
                 f"% lambda(t) from twod_<T>.npz, B_2 spline with m = {config.M_SPLINE[2]}; "
                 "|Delta x| is the Euclidean norm of the\n% point (original units); law from "
                 "twod_eval_<T>.npz. Blocks only for the targets whose result is present.\n")
    note += "\n".join(tvnote) + ("\n" if tvnote else "")
    used = ["integration_error", "oned_eval"] + [
        nm for c, _, lawsrc, _ in blocks[len(C.DATASETS):]
        for nm in (tname("integration_error", c), lawsrc)]
    return tab, note, used


