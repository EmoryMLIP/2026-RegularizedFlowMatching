    for _, grp in TWOD_SPAN.get(target, []) + TWOD_SPAN_UNREG:
        out.append(r"\addlinespace")
        for m, lab in grp:
            cells = [r"\multicolumn{2}{c}{" + _tv_text(cell(tv(m, n)), m in picked) + "}"
                     for n in C.SIZES]
