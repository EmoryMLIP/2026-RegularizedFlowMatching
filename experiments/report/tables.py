def ie_rk(ie):
    """[(integrator key, step count)] of the RK4 runs of integration_error.npz, production
    first; without the file, the step counts of config.INTEGRATION_ERROR."""
    if ie is None or "integrators" not in ie:
        ks = [int(round(f * config.NSTEP)) for f in config.INTEGRATION_ERROR["step_factors"]]
        return [(f"rk{k}", k) for k in ks]
    k0 = nstep(ie)
    ks = sorted((int(str(g)[2:]) for g in np.atleast_1d(ie["integrators"])
                 if str(g).startswith("rk")), key=lambda k: (k != k0, k))
    return [(f"rk{k}", k) for k in ks]


