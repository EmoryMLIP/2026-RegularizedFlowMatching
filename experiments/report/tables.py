def lam_sweep_values(d, target) -> dict:
    """Per-penalty curves and summary numbers of one lam_sweep file:
    scale (s, mean, se), const (c/c0, mean, se), ref (hold-out lam(t) mean, se), sel (median
    selected c/c0, mean and se over sets of tv_pos at each set's sel_idx; sel_tv the per-set
    values). sel_idx < 0 is lam_sweep.assemble's 'no selection' (crit_sum NaN everywhere):
    that set counts as missing (NaN in sel_tv, left out of the median), never as index -1."""
    sc, co = f"{target}/scale", f"{target}/const"
    s = np.asarray(d[f"{sc}/s"], float)
    rel = np.asarray(d[f"{co}/c"], float) / float(d[f"{co}/c0"])
    tvs, tvc = np.asarray(d[f"{sc}/tv_pos"], float), np.asarray(d[f"{co}/tv_pos"], float)
    ref = np.asarray(d[f"{target}/holdout_ref/tv_pos"], float)
    sel = np.asarray(d[f"{co}/sel_idx"], int)
    sek = f"{co}/tv_pos_se"
    sec = np.asarray(d[sek], float) if sek in d else np.full(tvc.shape, np.nan)

    def stat(a):
        return np.array([C.mean_se(a[:, j]) for j in range(a.shape[1])]).T

    (ms, ss), (mc, sc_) = stat(tvs), stat(tvc)
    j1 = int(np.argmin(np.abs(np.log10(s))))
    ok = sel >= 0
    sel_tv = np.full(len(sel), np.nan)
    sel_tv[ok] = tvc[np.flatnonzero(ok), sel[ok]]
    sel_tv_se = np.full(len(sel), np.nan)
    sel_tv_se[ok] = sec[np.flatnonzero(ok), sel[ok]]
    return {"s": s, "scale": ms, "scale_se": ss, "rel": rel, "const": mc, "const_se": sc_,
            "ref": C.mean_se(ref),
            "sel_rel": float(np.median(rel[sel[ok]])) if ok.any() else np.nan,
            "sel": C.mean_se(sel_tv), "sel_tv": sel_tv, "sel_tv_se": sel_tv_se, "sel_idx": sel,
            "s1_diff": float(np.max(np.abs(tvs[:, j1] - ref)))}


def _nfin(a) -> int:
    return int(np.count_nonzero(np.isfinite(np.asarray(a, float))))


def _nanargmin(m):
    """Index of the lowest finite entry, None if there is none (an all-NaN block)."""
    return int(np.nanargmin(m)) if np.isfinite(m).any() else None


def ls_at_edge(j, means) -> bool:
    """True if column j is the outermost column with a finite mean on either side: a column
    NaN in every set is not part of the grid, so a minimum next to it is at the grid end."""
    fin = np.flatnonzero(np.isfinite(np.asarray(means, float)))
    return j is not None and fin.size > 0 and j in (fin[0], fin[-1])


def lam_sweep_summary(d, target) -> dict:
    """The numbers of one tab_lam_sweep_full row, each (mean, SE) of tv_pos over the finite sets:
    holdout (hold-out lambda(t)), best_s and best_s_tv (scale with the lowest mean TV),
    best_const (constant with the lowest mean TV; best_const_rel its c/c0, best_const_edge
    true at a grid end), holdout_const (each set's hold-out constant, sel_idx).
    <key>_k: number of sets with a finite TV behind each of the four TV entries (of nsets);
    the table marks a cell with k < nsets. nan_blocks: the blocks (holdout_ref, scale,
    const) whose tv_pos is NaN in every set; their entries are NaN (best_s NaN, edge false),
    not an exception. The argmin runs over the means over the finite sets of each column."""
    v = lam_sweep_values(d, target)
    tvs = np.asarray(d[f"{target}/scale/tv_pos"], float)
    tvc = np.asarray(d[f"{target}/const/tv_pos"], float)
    ref = np.asarray(d[f"{target}/holdout_ref/tv_pos"], float)
    js, jc = _nanargmin(v["scale"]), _nanargmin(v["const"])
    nan2 = (np.nan, np.nan)
    return {"nsets": int(tvs.shape[0]),
            "nan_blocks": [b for b, a in (("holdout_ref", ref), ("scale", tvs), ("const", tvc))
                           if not np.isfinite(a).any()],
            "holdout": v["ref"], "holdout_k": _nfin(ref),
            "best_s": np.nan if js is None else float(v["s"][js]),
            "best_s_tv": nan2 if js is None else (float(v["scale"][js]), float(v["scale_se"][js])),
            "best_s_tv_k": 0 if js is None else _nfin(tvs[:, js]),
            "best_s_edge": ls_at_edge(js, v["scale"]),
            "best_const": nan2 if jc is None else (float(v["const"][jc]), float(v["const_se"][jc])),
            "best_const_k": 0 if jc is None else _nfin(tvc[:, jc]),
            "best_const_rel": np.nan if jc is None else float(v["rel"][jc]),
            "best_const_edge": ls_at_edge(jc, v["const"]),
            "holdout_const": v["sel"], "holdout_const_rel": v["sel_rel"],
            "holdout_const_k": _nfin(v["sel_tv"])}


def scale_label(s) -> str:
    """A scale factor 10^(k/2) as LaTeX: '$1$', '$10^{2}$', '$10^{0.5}$', '$10^{-0.5}$'."""
    k = int(round(2 * np.log10(s)))
    if k == 0:
        return "$1$"
    return f"$10^{{{k // 2}}}$" if k % 2 == 0 else f"$10^{{{k / 2:g}}}$"


# The four TV columns of tab_lam_sweep_full share one power of ten (render groups), so that
# the hold-out, scaled and constant columns compare digit by digit; per-column powers
# would give the H2 best-constant column 10^-1 and the others 10^-2.
LS_TV_KEYS = ("holdout", "best_s_tv", "best_const", "holdout_const")
LS_TV_COLS = (0, 2, 3, 4)   # cell columns of LS_TV_KEYS (column 1 is the scale s)
LS_COL_NAME = {"holdout": "hold-out lambda(t)", "best_s_tv": "TV at best alpha",
               "best_const": "best constant", "holdout_const": "hold-out constant"}
# cells that print \tbd when a block of the sweep is NaN in every set
LS_NAN_CELLS = {"holdout_ref": "hold-out lambda(t)",
                "scale": "best scale alpha and TV at best alpha",
                "const": "best constant and hold-out constant"}
# Cell markers (superscripts after the entry): a lowest mean TV at an end of the swept grid
# (the optimum may lie outside it), and a mean over k < K sets because the TV of the
# other sets is NaN. ls_caption_note gives the sentence the caption needs when one is used.
LS_MARK_EDGE, LS_MARK_PART = r"\ddag", r"\dag"


def ls_mark(edge=False, k=None, nsets=None) -> str:
    """Superscript marker of one TV cell: '\\textsuperscript{\\ddag}' at a grid end,
    '\\textsuperscript{\\dag 4}' for a mean over 4 of nsets sets, both comma-separated; ''
    if neither (and for k = 0, a cell that prints \\tbd)."""
    parts = ([LS_MARK_EDGE] if edge else []) + (
        [f"{LS_MARK_PART} {k}"] if k is not None and 0 < k < nsets else [])
    return r"\textsuperscript{" + ",".join(parts) + "}" if parts else ""


def ls_caption_note(marks, nsets) -> str:
    """Caption sentences for the markers in marks ({'edge', 'part'}); '' if none."""
    out = []
    if "edge" in marks:
        out.append(r"\textsuperscript{\ddag}Lowest mean TV at an end of the swept $\lambda$ "
                   "grid; the optimum may lie outside it.")
    if "part" in marks:
        out.append(fr"\textsuperscript{{\dag $k$}}Mean and SE over the $k$ of the {nsets} "
                   "training sets whose TV is finite.")
    return " ".join(out)


def _ls_e(x) -> str:
    return f"10^{np.log10(x):+.1f}" if np.isfinite(x) else "n/a"


def _ls_ms(m) -> str:
    return f"{m[0]:.4f} +- {m[1]:.4f}" if np.isfinite(m[0]) else "n/a"


def _ls_row(d, lab, reg, target, prefix):
    """One penalty row of tab_lam_sweep_full: (row, note lines, marked-cell
    lines, marks used, nsets). prefix opens the note lines ('% circle B_2:')."""
    if d is None:
        tbd = Cell(np.nan, np.nan, False, True)
        return ([lab], [tbd, C.tbd(), tbd, tbd, tbd]), [], [], set(), None
    v = lam_sweep_summary(d, target)
    sf = (" (grid end)" if v["best_s_edge"] else "")
    cf = (" (grid end)" if v["best_const_edge"] else "")
    notes = [f"{prefix} hold-out lambda(t) {_ls_ms(v['holdout'])};"
             f" best alpha = {_ls_e(v['best_s'])}{sf}: {_ls_ms(v['best_s_tv'])};",
             f"%   best constant (kappa/kappa0 = {_ls_e(v['best_const_rel'])}{cf}): "
             f"{_ls_ms(v['best_const'])}; hold-out constant "
             f"(median kappa/kappa0 = {_ls_e(v['holdout_const_rel'])}): {_ls_ms(v['holdout_const'])}"]
    for b in v["nan_blocks"]:
        notes.append(f"%   {target}/{b}/tv_pos is NaN in every set: {LS_NAN_CELLS[b]} print \\tbd")
    edge = {"best_s_tv": v["best_s_edge"], "best_const": v["best_const_edge"]}
    cells, marked, marks = [], [], set()
    for key in LS_TV_KEYS:
        k, e = v[f"{key}_k"], edge.get(key, False)
        mk = ls_mark(e, k, v["nsets"])
        cells.append(Cell(*v[key], False, k == 0, mk))
        if e:
            marks.add("edge")
            marked.append(f"{prefix} {LS_COL_NAME[key]}: lowest mean TV at a grid end (\\ddag)")
        if 0 < k < v["nsets"]:
            marks.add("part")
            marked.append(f"{prefix} {LS_COL_NAME[key]}: mean over {k} of {v['nsets']} sets "
                          "(tv_pos NaN in the others; \\dag)")
    s_txt = C.tbd() if not np.isfinite(v["best_s"]) else scale_label(v["best_s"])
    return ([lab], [cells[0], s_txt] + cells[1:]), notes, marked, marks, v["nsets"]


def _ls_mark_lines(marked, marks, nsets) -> list:
    """Header lines listing the marked cells and the caption sentence (none if unmarked)."""
    if not marks:
        return []
    return (["% Marked cells:"] + marked
            + [f"% caption note for the markers: {ls_caption_note(marks, max(nsets))}"])


