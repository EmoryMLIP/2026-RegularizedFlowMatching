def main_const(S: Sources, case: str, n: int):
    """Per-set tv_pos of the H2 flow with the hold-out constant lambda(t) = kappa (lam_sweep
    sel_tv, the 'hold-out constant' column of tab_lam_sweep_full) at N = n (main_const_source):
    PENDING if the file is missing (every N is expected), None (printed '--') if the file
    records another N."""
    _, d = main_const_source(S, case, n)
