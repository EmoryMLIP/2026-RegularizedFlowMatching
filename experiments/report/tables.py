def _ie_cell(v, how):
    return C.tbd() if v is PENDING else C.fmt_e(how(v) if v is not None else np.nan)


def _max_dx(a):
    """max over sets and latents of |Delta x|: |.| the absolute value in 1D (a (sets, m)), the
    Euclidean norm of the point in 2D (a (sets, m, D))."""
    a = np.asarray(a, float)
    return np.nanmax(np.abs(a)) if a.ndim < 3 else np.nanmax(np.sqrt(np.sum(a * a, axis=-1)))


