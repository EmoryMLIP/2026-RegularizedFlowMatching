def tab_lam_sweep_full(S: Sources) -> str:
    """Appendix table: sensitivity to lambda(t) for every target of LS_TARGETS (one \\emph
    group row per target, then one row per penalty, B_2, B_1, B_0); one power of ten for the
    four TV columns over the whole table."""
    used = [ls_name(t, reg) for t, _ in LS_TARGETS for reg, _ in REG_PENALTIES]
    notes = [S.header(used).rstrip("\n")]
    for t, _ in LS_TARGETS:
        for reg, _ in REG_PENALTIES:
            notes += ls_check(S[ls_name(t, reg)], t, reg)
    body, rows_notes, marked, marks, nsets = [], [], [], set(), []
    for target, label in LS_TARGETS:
        body += [r"\midrule", fr"\multicolumn{{6}}{{l}}{{\emph{{{dim_label(target, label)}}}}} \\"]
        for reg, _ in REG_PENALTIES:
            row, nt, mk, ms, ns = _ls_row(S[ls_name(target, reg)], C.penalty_label(reg), reg,
                                          target, f"% {target} B_{C.PENALTY_OP[reg]}:")
            body.append(row)
            rows_notes += nt
            marked += mk
            marks |= ms
            nsets += [ns] if ns else []
    lines, exps = render(body, groups=[LS_TV_COLS])
    e = exps[LS_TV_COLS[0]] if exps else 0
    unit = f"10^{e}" if e else "no power (no results yet)"
    notes += [f"% lambda sweep at N = {LS_N} (compute/lam_sweep.py; the file's n) for every target: Trimodal and",
              "% Inhomogeneous (1D), Noisy circle, Checkerboard, Two spirals, 8 Gaussians (2D); per",
              "% target the penalties B_2, B_1, B_0 (h2, h1, l2). Columns: hold-out lambda(t)",
              "% (<target>/holdout_ref); best scale alpha of lambda(t) = alpha lambda_holdout(t) and its",
              "% TV; best constant lambda(t) = kappa; hold-out constant (tv_pos at each set's sel_idx).",
              "% TV = tv_pos, mean \\pm SE over the training sets. The four TV columns share one",
              "% power of ten over the whole table, set by the smallest mean (header row; "
              f"{unit} for",
              "% these results)."]
    notes += rows_notes + _ls_mark_lines(marked, marks, nsets)
    tab = LS_HEAD + power_row(1, exps) + lines + [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(notes) + "\n" + "\n".join(tab) + "\n"


