PENDING = _Pending()


class Vals(np.ndarray):
    """Per-set values with their per-set Monte Carlo SEs `se` (None if not stored)."""

    se = None

    def __array_finalize__(self, obj):
        self.se = getattr(obj, "se", None)


def with_se(v, se):
    """v (per-set values) as Vals carrying se; None stays None."""
    if v is None:
        return None
    out = np.asarray(v, float).view(Vals)
    out.se = None if se is None else np.asarray(se, float)
    return out


def is_tv_key(key) -> bool:
    """A TV estimate (tv_pos, tv_iid, tv_law, tv_grid, tv, tv_pos_<rule>): stored with its
    Monte Carlo SE '<key>_se'."""
    last = key.rsplit("/", 1)[-1]
    return last == "tv" or last.startswith("tv_")


def rowv(d, key, n):
    """C.row of key with its Monte Carlo SE '<key>_se' attached for a TV key."""
    v = C.row(d, key, n)
    if v is None or not is_tv_key(key):
        return with_se(v, None)
    se = C.row(d, key + "_se", n) if d.has(key + "_se") else None
    return with_se(v, se)


def rowp(d, key, n):
    """rowv, or PENDING if the source d is missing."""
    return PENDING if d is None else rowv(d, key, n)


def rowq(d, key, n, need):
    """rowp per cell: also PENDING (\\tbd) where the source exists but lacks the cell although
    config requires it (n in need; a result that lacks an N config asks for, to be rerun).
    Smoke directories hold one N, so there the cell prints '--'."""
    v = rowp(d, key, n)
    if v is None and n in need and not (C.RES is not None and C.RES.smoke):
        return PENDING
    return v


def stats(v):
    """(mean, SE over sets) of per-set values; NaN for a pending or missing entry."""
    return (np.nan, np.nan) if v is PENDING else C.mean_se(v)


def mc_of(v) -> float:
    """Monte Carlo SE of the mean over sets of v (common.mc_se of its per-set SEs)."""
    return np.nan if v is None or v is PENDING else C.mc_se(getattr(v, "se", None))


def unresolved_vs(a, b) -> bool:
    """The unresolved rule for two per-set arrays (common.unresolved): their means over sets differ by
    less than twice the combined Monte Carlo SE, or by less than twice the SE over sets of
    the per-set differences (spread; only when both have the same sets)."""
    if a is None or b is None or a is PENDING or b is PENDING:
        return False
    ma, mb = stats(a)[0], stats(b)[0]
    spread = None
    x, y = np.asarray(a, float).ravel(), np.asarray(b, float).ravel()
    if x.shape == y.shape:
        ok = np.isfinite(x) & np.isfinite(y)
        if ok.sum() >= 2:
            spread = 2.0 * C.mean_se(x[ok] - y[ok])[1]
    return C.unresolved(ma, mc_of(a), mb, mc_of(b), spread=spread)


