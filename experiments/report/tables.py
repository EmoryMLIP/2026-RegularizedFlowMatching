class Sources:
    """The result files the tables read, through common.load (None if missing); `used`
    collects the names a table read for its header."""

    def __getitem__(self, nm):
        return C.load(nm)

    def header(self, used) -> str:
        used = list(dict.fromkeys(used))
        lines = [GENERATED, C.results_line()] + [C.src_line(nm) for nm in used]
        missing = [nm for nm in used if C.load(nm) is None]
