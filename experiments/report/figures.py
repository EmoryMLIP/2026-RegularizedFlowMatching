COLORS = {"rblue": "0072B2", "rverm": "D55E00", "rgreen": "009E73", "rpurple": "CC79A7"}


def _color_defs() -> str:
    return "".join(f"\\definecolor{{{k}}}{{HTML}}{{{v}}}\n" for k, v in COLORS.items())


def _standalone(name, comments, body, resize=False) -> str:
    """The standalone document of a figure; resize: the paper scales it to \\textwidth."""
    use = (f"\\resizebox{{\\textwidth}}{{!}}{{\\input{{figures/{name}.tex}}}}" if resize
           else f"\\input{{figures/{name}.tex}}")
    return (GENERATED + "\n" + C.results_line() + "\n"
            "% Standalone: pdflatex " + name + ".tex in this directory. In the paper:\n"
            "% \\usepackage{standalone} (strips this preamble) and\n% \\newcommand{\\figdir}{figures}" + use + "\n"
            + "\n".join(comments) + "\n"
            "\\documentclass{standalone}\n"
            "\\usepackage{pgfplots}\n\\usepgfplotslibrary{groupplots}\n"
            "\\usetikzlibrary{calc}\n\\pgfplotsset{compat=1.18}\n"
            "\\providecommand{\\figdir}{.}\n"
            "\\begin{document}\n\\begin{tikzpicture}\n" + body
            + "\\end{tikzpicture}\n\\end{document}\n")


def _dir_files(sub):
    """Paths relative to C.OUT of the files in C.FIGURES/sub (sorted)."""
    p = os.path.join(C.FIGURES, sub)
    return sorted(f"figures/{sub}/{f}" for f in os.listdir(p)) if os.path.isdir(p) else []


