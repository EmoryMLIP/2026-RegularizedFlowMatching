def _twod_files(target):
    """(twod_eval_<T>, kde4_2d_<T>) Stores (None if missing)."""
    return C.load(T.tname("twod_eval", target)), C.load(T.tname("kde4_2d", target))


def _twod_tv(target, m):
    """Per-(n, set) tv_pos of method m (flow or KDE) of a target from the first source holding
    it; the second-order KDEs fall back to kde2d_<T>."""
    ev, k4 = _twod_files(target)
    if m.startswith("k4"):
        return C.get(k4, T.kde4_2d_key(k4, target, m, "tv_pos"))
    v = C.get(ev, f"{target}/{m}/tv_pos")
    if (v is None or not np.isfinite(v).any()) and m.startswith("kde_"):
        kd = C.load(T.tname("kde2d", target))
        w = C.get(kd, T.kde2d_key(kd, target, m, "tv_pos"))
        v = v if w is None else w
    return v


def _image(d, key, n):
    """Image row of N = n of key (float32 for every reader, common.Store.image), or None."""
    j = C.n_index(d, n)
    if j is None or key not in d:
        return None
    im = d.image(key)[j]
    return None if not np.isfinite(im).any() else np.asarray(im, float)


def _twod_image(target, m, n):
    """Density image (ij indexing on xf2) of method m of a target at the representative set
    of n, or None."""
    ev, k4 = _twod_files(target)
    if m.startswith("k4"):
        return None if k4 is None else _image(k4, T.kde4_2d_key(k4, target, m, "image"), n)
    return None if ev is None else _image(ev, f"{target}/{m}/image", n)


def _twod_extent(xf2):
    """(lo, hi): the outer pixel edges of the image grid xf2 (pixel centres)."""
    dx = xf2[1] - xf2[0]
    return xf2[0] - dx / 2, xf2[-1] + dx / 2


def _twod_true(ev, target):
    """True density of a target on xf2 from its twod_eval Store, or None."""
    k = f"{target}/pdf_true"
    if ev is None or k not in ev:
        return None
    true = np.asarray(ev.image(k), float)
    return np.where(np.isfinite(true), true, 0.0)


def _twod_vmax(true):
    """Top of a target's color scale: 1.1 max of the true density (1 without it)."""
    return 1.1 * float(np.nanmax(true)) if true is not None else 1.0


def _density_png(rel, img, vmax):
    """Write the densblue PNG of a density image (ij indexing on xf2) to C.FIGURES/rel."""
    C.write_png(os.path.join(C.FIGURES, rel), C.colorize(C.grid_image(img), vmax))


def _graphics(rel, lo, hi) -> str:
    return (f"\\addplot graphics[xmin={lo:.6g}, xmax={hi:.6g}, ymin={lo:.6g}, ymax={hi:.6g}] "
            f"{{\\figdir/{rel}}};\n")


def _tv_node(v) -> str:
    """TV tag at the bottom right of an image panel ('' for NaN)."""
    if not np.isfinite(v):
        return ""
    return ("\\node[anchor=south east, font=\\scriptsize, fill=white, fill opacity=0.7, "
            "text opacity=1, inner sep=1.5pt] at (rel axis cs:0.97,0.03) "
            f"{{TV {v:.3f}}};\n")


def _twod_best_kde(target):
    """(method, {method: mean tv_pos}) of the best data-driven KDE of a target: the lowest
    mean tv_pos over all N and sets among KDE2_DD (kde_fix_lscv without results)."""
    scores = {m: float(np.nanmean(v)) for m in KDE2_DD
              if (v := _twod_tv(target, m)) is not None and np.isfinite(v).any()}
    return (min(scores, key=scores.get) if scores else "kde_fix_lscv"), scores


def _operator_name(target, reg) -> str:
    """twod_eval result of a penalty's flows: twod_eval_<T>[_<reg>]."""
    return T.tname("twod_eval", target) + T._reg_sfx(reg)


def _operator_eval(target, reg):
    return C.load(_operator_name(target, reg))


def _operator_panel(ev, target, n):
    """(image, set, tv_pos) of the hold-out flow in a twod_eval Store at N = n: the stored image
    of its representative set rep_set and the TV of that set; None if anything is missing."""
    j = C.n_index(ev, n)
    if j is None:
        return None
    rep, tv = C.get(ev, f"{target}/rep_set"), C.get(ev, f"{target}/holdout/tv_pos")
    img = _image(ev, f"{target}/holdout/image", n)
    if rep is None or tv is None or img is None:
        return None
    s = int(rep[j])
    return img, s, float(tv[j, s])


TWOD_OPS_N = 1000
TWOD_OPS_PRINT_CM = 13.02
TWOD_OPS_PANEL_CM = 2.2          # side of one square image panel
TWOD_OPS_SEP_CM = 0.1            # horizontal and vertical sep between panels
TWOD_OPS_REGS = ["l2", "h1", "h2"]   # column order: weakest to strongest smoothness
# the penalty titles on two lines ('smallness \\($k = 0$)'), which needs align=center in the
# title style (pdflatex: 'Not allowed in LR mode' otherwise)
TWOD_OPS_TITLE = {**{r: C.penalty_label(r).replace(" (", " \\\\(", 1) for r in TWOD_OPS_REGS},
                  "kde": "best KDE", "true": "true density"}
TWOD_OPS_KDE = {"kde_fix_lscv": "KDE, LSCV", "kde_abr_lscv": "Abramson\\\\LSCV",
                "k4_lscv": "4th order\\\\LSCV", "k4p_lscv": "4th order,\\\\product, LSCV"}
TWOD_OPS_YLAB_CM = 0.55
TWOD_OPS_CBAR_CM = 0.15 + 0.12 + 0.75
TWOD_OPS_MIN_PT = 7.0
TWOD_OPS_TICK_PT = 7.0           # \scriptsize in a 10 pt document: TV tags, KDE names


def twod_ops_width() -> float:
    """Estimated width (cm) of fig_twod_ops: row label, five panels, four seps, colorbar."""
    return (TWOD_OPS_YLAB_CM + 5 * TWOD_OPS_PANEL_CM + 4 * TWOD_OPS_SEP_CM + TWOD_OPS_CBAR_CM)


def _twod_kde_panel(target, m, n):
    """(image, set, tv_pos) of KDE m of a target at N = n: the stored image of the
    representative set of the file that holds it (kde4_2d for 'k4*', else twod_eval) and the
    tv_pos of that set; None if missing."""
    ev, k4 = _twod_files(target)
    d = k4 if m.startswith("k4") else ev
    j = C.n_index(d, n)
    if j is None:
        return None
    rep = C.get(d, T.first_key(d, [f"{target}/rep_set", "rep_set"]))
    img = _twod_image(target, m, n)
    tv = _twod_tv(target, m)
    if rep is None or img is None or tv is None:
        return None
    s = int(rep[j])
    return img, s, float(tv[j, s])


def fig_twod_ops(S) -> list:
    """Densities of the 2D targets under the three penalties, the best KDE and the truth."""
    width = twod_ops_width()
    tick_pt = TWOD_OPS_TICK_PT * TWOD_OPS_PRINT_CM / width if width > TWOD_OPS_PRINT_CM else TWOD_OPS_TICK_PT
    if tick_pt < TWOD_OPS_MIN_PT:
        raise ValueError(f"fig_twod_ops: estimated width {width:.2f} cm exceeds "
                         f"{TWOD_OPS_PRINT_CM} cm; printed ticks {tick_pt:.1f} pt < {TWOD_OPS_MIN_PT} pt")
    srcs = [C.src_line(nm) for t, _ in T.TWOD_CASES
            for nm in [_operator_name(t, r) for r in TWOD_OPS_REGS]
            + [T.tname("kde4_2d", t), T.tname("kde2d", t)]]
    notes = srcs + [
        f"% Densities at N = {TWOD_OPS_N} (or the N of the files closest to it): rows the 2D",
        "% targets, columns the FM flows with the B_0 / B_1 / B_2 penalty (hold-out lambda(t)), the",
        "% best data-driven KDE of the target (lowest mean tv_pos over all N and sets among",
        "% tables.TWOD_KDE_DD) and the true density. Flow images: <T>/holdout/image of",
        "% twod_eval_<T>[_<reg>].npz, each at the representative set <T>/rep_set of its file (median",
        "% hold-out tv_pos of that penalty), so the set can differ between columns. KDE image: the",
        "% stored image of kde4_2d_<T> (4th-order KDEs) or twod_eval_<T> (2nd-order), at that",
        "% file's rep_set. TV tag: tv_pos of the shown set.",
        "% One color scale per row (0 .. 1.1 max of the true density of the target, from the B_2",
        "% file; values above saturate, fraction of saturated pixels per panel below), shared by",
        "% the five columns, pgfplots colormap 'densblue' identical to the PNG colors.",
        f"% figure width {width:.2f} cm (estimate; not resized in the paper); printed sizes:",
        f"% TV tags and KDE names {tick_pt:.1f} pt (\\scriptsize), colorbar ticks 8 pt (\\footnotesize), titles and row labels 9 pt (\\small)"]
    cols = [(r, TWOD_OPS_TITLE[r]) for r in TWOD_OPS_REGS] + [("kde", TWOD_OPS_TITLE["kde"]),
                                                             ("true", TWOD_OPS_TITLE["true"])]
    P, sep = f"{TWOD_OPS_PANEL_CM}cm", f"{TWOD_OPS_SEP_CM}cm"
    panels, written, peaks = [], [], {}
    for r, (target, label) in enumerate(T.TWOD_CASES):
        ev = _twod_files(target)[0]
        evname = T.tname("twod_eval", target)
        n = C.pick_n(ev, TWOD_OPS_N) or TWOD_OPS_N
        xf2 = np.asarray(ev["xf2"], float) if ev is not None and "xf2" in ev else TWOD_BLANK_GRID
        lo, hi = _twod_extent(xf2)
        true = _twod_true(ev, target)
        vmax = _twod_vmax(true)
        best, scores = _twod_best_kde(target)
        ranking = ", ".join(f"{m} {v:.4f}" for m, v in sorted(scores.items(), key=lambda kv: kv[1]))
        notes.append(f"% {target}: N = {n}; color scale 0 .. {vmax:.4g}; grid {xf2[0]:g} .. "
                     f"{xf2[-1]:g}, {xf2.size} points per axis (from {evname}.npz); KDE {best} "
                     f"({KDE2_LABEL.get(best, best)}; ranking {ranking})")
        for c, (key, title) in enumerate(cols):
            opts = []
            if r == 0:
                opts.append(f"title={{{title}}}")
            if c == 0:
                opts.append(f"ylabel={{{label}}}")
            opts += [f"xmin={lo:.6g}", f"xmax={hi:.6g}", f"ymin={lo:.6g}", f"ymax={hi:.6g}",
                     f"point meta min=0, point meta max={vmax:.6g}"]
            if c == len(cols) - 1:
                opts.append("colorbar, colorbar style={at={(1.07,0.5)}, anchor=west, "
                            f"height={P}, width=0.12cm, scale only axis, axis equal image=false, "
                            "scaled ticks=false, tick label style={font=\\footnotesize, "
                            "/pgf/number format/fixed}}")
            p = f"\\nextgroupplot[{', '.join(opts)}]\n"
            if key == "true":
                got = None if true is None else (true, None, np.nan)
                src_txt = f"{evname}.npz"
            elif key == "kde":
                got = _twod_kde_panel(target, best, n)
                src_txt = f"{T.tname('kde4_2d' if best.startswith('k4') else 'twod_eval', target)}.npz"
            else:
                rev = _operator_eval(target, key)
                got = _operator_panel(rev, target, n)
                if got is not None and not np.allclose(rev["xf2"], xf2):
                    raise ValueError(f"{_operator_name(target, key)}: image grid differs from "
                                     f"that of {evname} ({target})")
                src_txt = f"{_operator_name(target, key)}.npz"
            if got is None:
                p += PENDING_PANEL
                notes.append(f"% {target} {key}: PENDING (source {src_txt} missing or without the image)")
            else:
                img, s, tv = got
                rel = f"fig_twod_ops/{target}_{key}.png"
                _density_png(rel, img, vmax)
                written.append("figures/" + rel)
                p += _graphics(rel, lo, hi) + _tv_node(tv)
                if key == "kde":
                    p += ("\\node[anchor=north west, font=\\scriptsize, align=left, fill=white, "
                          "fill opacity=0.7, text opacity=1, inner sep=1.5pt] at (rel axis cs:0.03,0.97) "
                          f"{{{TWOD_OPS_KDE.get(best, best)}}};\n")
                sat = float(np.mean(np.nan_to_num(img) > vmax))
                peak = float(np.nanmax(img) / vmax)
                if true is not None and key != "true":
                    peaks.setdefault(key, {})[target] = float(np.nanmax(img) / np.nanmax(true))
                what = "true density" if key == "true" else f"set {s}, tv_pos {tv:.4f}"
                notes.append(f"% {target} {key}: {what}, saturated {100 * sat:.2f}% of pixels "
                             f"(max {peak:.3g} x the top); source {src_txt}")
            panels.append(p)
    for reg in TWOD_OPS_REGS:
        pk = peaks.get(reg, {})
        if pk:
            # sec:operator quotes the B_0 (l2) peaks: 12 to 160 times the largest true density
            notes.append(f"% text number ({reg} peaks, sec:operator): max density over the max of "
                         "the true density "
                         f"{min(pk.values()):.3g} .. {max(pk.values()):.3g} x ("
                         + ", ".join(f"{t} {v:.3g}" for t, v in pk.items()) + ")")
    body = ("\\begin{groupplot}[group style={group size=" + f"{len(cols)} by {len(T.TWOD_CASES)}"
            + f", horizontal sep={sep}, vertical sep={sep}}},\n"
            f"  width={P}, height={P}, scale only axis, axis equal image,\n"
            "  xtick=\\empty, ytick=\\empty, enlargelimits=false, axis on top,\n"
            f"  {C.pgf_colormap()},\n"
            "  title style={font=\\small, inner sep=2pt, align=center}, ylabel style={font=\\small}]\n"
            + "".join(panels) + "\\end{groupplot}\n")
    C.write_text(os.path.join(C.FIGURES, "fig_twod_ops.tex"),
                 _standalone("fig_twod_ops", notes, body))
    return ["figures/fig_twod_ops.tex"] + sorted(written)


