"""pgfplots figures of the paper (report stage; seconds), from one results directory.
Paper: Figure 2 (fig:accuracy) and Figure 4 (fig:twod-ops).

build() writes OUT/figures/:
  fig_twod_ops.tex, fig_twod_ops/<target>_<l2|h1|h2|kde|true>.png
      densities at N = 1000: rows the 2D targets, columns the B_0 / B_1 / B_2 hold-out flows
      (twod_eval_<T>[_<reg>], each at its own file's rep_set), the best data-driven KDE
      (tables.TWOD_KDE_DD; twod_eval_<T> or kde4_2d_<T>) and the true density; one colour
      scale per row (0 .. 1.1 max p). The header prints the B_0 peaks over the colour top (the
      12-162x text number of sec:operator).
  fig_accuracy.tex, fig_accuracy/<case>.dat
      TV (mean +- SE) against the spline resolution m at N = 1000 for the trimodal density,
      the circle and the spirals (ACC_CASES, one data file each): B_2
      lambda -> 0 (controls_iid_<case>), B_2 / B_1 / B_0 hold-out (controls_<case>[_<reg>]),
      the circle's extra resolution from controls_circle[_<reg>]_m512 and
      controls_iid_circle_m512.
Penalty labels: common.penalty_label.
The .tex files are standalone (pdflatex in OUT/figures/) and read their data through \\figdir
(default '.'); in the paper \\newcommand{\\figdir}{figures} before \\input. A panel whose source
is missing says 'pending' (never \\tbd); the header names the missing files.
"""

